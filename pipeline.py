class SD2Pipeline(StableDiffusionPipeline):
    @torch.no_grad()
    def __call__(
        self,
        prompt: Union[str, List[str]],
        prompt1_steps: Optional[int] = None,
        prompt2: Optional[str] = None,
        timesteps=None,
        head_start_latents: Optional[Union[torch.FloatTensor, list]] = None,
        head_start_step: Optional[int] = None,
        height: Optional[int] = None,
        width: Optional[int] = None,
        num_inference_steps: int = 50,
        guidance_scale: float = 7.5,
        negative_prompt: Optional[Union[str, List[str]]] = None,
        num_images_per_prompt: Optional[int] = 1,
        eta: float = 0.0,
        generator: Optional[torch.Generator] = None,
        latents: Optional[torch.FloatTensor] = None,
        output_type: Optional[str] = "pil",
        return_dict: bool = True,
        callback: Optional[Callable[[int, int, torch.FloatTensor], None]] = None,
        callback_steps: Optional[int] = 1,
        verbose: Optional[bool] = False,
        early_steps_timesteps: Optional[List[int] | None | torch.Tensor] = None,
    ):
        r"""
        Function invoked when calling the pipeline for generation.

        Args:
            prompt (`str` or `List[str]`):
                The prompt or prompts to guide the image generation.
            height (`int`, *optional*, defaults to self.unet.config.sample_size * self.vae_scale_factor):
                The height in pixels of the generated image.
            width (`int`, *optional*, defaults to self.unet.config.sample_size * self.vae_scale_factor):
                The width in pixels of the generated image.
            num_inference_steps (`int`, *optional*, defaults to 50):
                The number of denoising steps. More denoising steps usually lead to a higher quality image at the
                expense of slower inference.
            guidance_scale (`float`, *optional*, defaults to 7.5):
                Guidance scale as defined in [Classifier-Free Diffusion Guidance](https://arxiv.org/abs/2207.12598).
                `guidance_scale` is defined as `w` of equation 2. of [Imagen
                Paper](https://arxiv.org/pdf/2205.11487.pdf). Guidance scale is enabled by setting `guidance_scale >
                1`. Higher guidance scale encourages to generate images that are closely linked to the text `prompt`,
                usually at the expense of lower image quality.
            negative_prompt (`str` or `List[str]`, *optional*):
                The prompt or prompts not to guide the image generation. Ignored when not using guidance (i.e., ignored
                if `guidance_scale` is less than `1`).
            num_images_per_prompt (`int`, *optional*, defaults to 1):
                The number of images to generate per prompt.
            eta (`float`, *optional*, defaults to 0.0):
                Corresponds to parameter eta (η) in the DDIM paper: https://arxiv.org/abs/2010.02502. Only applies to
                [`schedulers.DDIMScheduler`], will be ignored for others.
            generator (`torch.Generator`, *optional*):
                A [torch generator](https://pytorch.org/docs/stable/generated/torch.Generator.html) to make generation
                deterministic.
            latents (`torch.FloatTensor`, *optional*):
                Pre-generated noisy latents, sampled from a Gaussian distribution, to be used as inputs for image
                generation. Can be used to tweak the same generation with different prompts. If not provided, a latents
                tensor will ge generated by sampling using the supplied random `generator`.
            output_type (`str`, *optional*, defaults to `"pil"`):
                The output format of the generate image. Choose between
                [PIL](https://pillow.readthedocs.io/en/stable/): `PIL.Image.Image` or `np.array`.
            return_dict (`bool`, *optional*, defaults to `True`):
                Whether or not to return a [`~pipelines.stable_diffusion.StableDiffusionPipelineOutput`] instead of a
                plain tuple.
            callback (`Callable`, *optional*):
                A function that will be called every `callback_steps` steps during inference. The function will be
                called with the following arguments: `callback(step: int, timestep: int, latents: torch.FloatTensor)`.
            callback_steps (`int`, *optional*, defaults to 1):
                The frequency at which the `callback` function will be called. If not specified, the callback will be
                called at every step.

        Returns:
            [`~pipelines.stable_diffusion.StableDiffusionPipelineOutput`] or `tuple`:
            [`~pipelines.stable_diffusion.StableDiffusionPipelineOutput`] if `return_dict` is True, otherwise a `tuple.
            When returning a tuple, the first element is a list with the generated images, and the second element is a
            list of `bool`s denoting whether the corresponding generated image likely represents "not-safe-for-work"
            (nsfw) content, according to the `safety_checker`.
        """
        # import pdb; pdb.set_trace()
        # 0. Default height and width to unet
        height = height or self.unet.config.sample_size * self.vae_scale_factor
        width = width or self.unet.config.sample_size * self.vae_scale_factor

        # 1. Check inputs. Raise error if not correct
        self.check_inputs(prompt, height, width, callback_steps)

        # 2. Define call parameters
        batch_size = 1 if isinstance(prompt, str) else len(prompt)
        device = self._execution_device
        # here `guidance_scale` is defined analog to the guidance weight `w` of equation (2)
        # of the Imagen paper: https://arxiv.org/pdf/2205.11487.pdf . `guidance_scale = 1`
        # corresponds to doing no classifier free guidance.
        do_classifier_free_guidance = guidance_scale > 1.0

        # 3. Encode input prompt
        text_embeddings = self._encode_prompt(
            prompt,
            device,
            num_images_per_prompt,
            do_classifier_free_guidance,
            negative_prompt,
        )

        if prompt2 is not None:
            text_embeddings2 = self._encode_prompt(
                prompt2,
                device,
                num_images_per_prompt,
                do_classifier_free_guidance,
                negative_prompt,
            )

        # 4. Prepare timesteps
        if timesteps is None:
            self.scheduler.set_timesteps(num_inference_steps, device=device)
            timesteps = self.scheduler.timesteps
        else:
            self.scheduler.timesteps = timesteps
        # print(timesteps)

        # 5. Prepare latent variables
        if head_start_latents is None:
            num_channels_latents = self.unet.in_channels
            latents = self.prepare_latents(
                batch_size * num_images_per_prompt,
                num_channels_latents,
                height,
                width,
                text_embeddings.dtype,
                device,
                generator,
                latents,
            )
        else:
            if type(head_start_latents) == list:
                latents = head_start_latents[-1]
                assert len(head_start_latents) == self.scheduler.config.solver_order

            else:
                latents = head_start_latents  # if there is a head start
                if verbose:
                    print(
                        f"Using provided head_start_latents with shape {latents.shape}"
                    )

        # 6. Prepare extra step kwargs. TODO: Logic should ideally just be moved out of the pipeline
        extra_step_kwargs = self.prepare_extra_step_kwargs(generator, eta)

        # 7. Denoising loop
        num_warmup_steps = len(timesteps) - num_inference_steps * self.scheduler.order
        with self.progress_bar(total=num_inference_steps) as progress_bar:
            
            if early_steps_timesteps is not None:
                if verbose:
                    print(
                        f"Using custom {len({early_steps_timesteps})}-steps early_steps_timesteps ({early_steps_timesteps}) instaed of {len(timesteps)}-steps scheduler timesteps ({timesteps})"
                    )
                if isinstance(early_steps_timesteps, list):
                    timesteps = torch.tensor(early_steps_timesteps).to(timesteps.device).to(timesteps.dtype)
                elif isinstance(early_steps_timesteps, torch.Tensor):
                    timesteps = early_steps_timesteps.to(timesteps.device).to(timesteps.dtype)
                else:
                    raise ValueError(
                        f"`early_steps_timesteps` must be a list or a torch.Tensor, but got {type(early_steps_timesteps)}"
                    )
            
            for i, t in enumerate(timesteps):
                # print((i, t))
                if (
                    not head_start_step or i >= head_start_step
                ):  # if there is no head start or we reached the hs step
                    # expand the latents if we are doing classifier free guidance
                    # print(latents.shape)
                    latent_model_input = (
                        torch.cat([latents] * 2)
                        if do_classifier_free_guidance
                        else latents
                    )
                    latent_model_input = self.scheduler.scale_model_input(
                        latent_model_input, t
                    )

                    # predict the noise residual
                    if prompt1_steps is None or i < prompt1_steps:
                        noise_pred = self.unet(
                            latent_model_input, t, encoder_hidden_states=text_embeddings
                        ).sample
                    else:
                        # print(f'i = {i}, atteding to prompt2')
                        noise_pred = self.unet(
                            latent_model_input,
                            t,
                            encoder_hidden_states=text_embeddings2,
                        ).sample

                    # perform guidance
                    if do_classifier_free_guidance:
                        noise_pred_uncond, noise_pred_text = noise_pred.chunk(2)
                        noise_pred = noise_pred_uncond + guidance_scale * (
                            noise_pred_text - noise_pred_uncond
                        )

                        # compute the previous noisy sample x_t -> x_t-1
                        latents = self.scheduler.step(
                            noise_pred, t, latents, **extra_step_kwargs
                        ).prev_sample
                else:
                    if verbose:
                        print(
                            f"Skipping denoising step {i} at timestep {t} due to head_start_step={head_start_step}"
                        )

                # call the callback, if provided
                if (i + 1) > num_warmup_steps and (i + 1) % self.scheduler.order == 0:
                    progress_bar.update()
                    if callback is not None and i % callback_steps == 0:
                        callback(i, t, latents)

        # 8. Post-processing
        image = self.decode_latents(latents)

        # 9. Run safety checker
        has_nsfw_concept = False
        # image, has_nsfw_concept = self.run_safety_checker(image, device, text_embeddings.dtype)

        # 10. Convert to PIL
        if output_type == "pil":
            image = self.numpy_to_pil(image)

        if not return_dict:
            return (image, has_nsfw_concept)

        return StableDiffusionPipelineOutput(
            images=image, nsfw_content_detected=has_nsfw_concept
        )

    def modm_image_to_latent(
        self,
        image: torch.Tensor,
        step: int,
        total_inference_steps: int,
        generator: Optional[torch.Generator] = None,
        verbose: bool = False,
    ) -> torch.Tensor:
        assert (
            image.dim() == 4 and image.size(0) == 1
        ), f"Input image must be a 4D tensor with batch size 1, but got shape {image.shape}"
        # 编码(1, 3, 768, 768)图像到(1, 4, 96, 96)潜在空间，并正则化
        encoded = self.vae.encode(image, return_dict=True)
        latents = encoded.latent_dist.sample(generator=generator)
        shift_factor, scaling_factor = 0.0, 1.0
        if hasattr(self.vae.config, "shift_factor"):
            if verbose:
                print(f"VAE config shift_factor: {self.vae.config.shift_factor}")
            shift_factor = (
                self.vae.config.shift_factor
                if self.vae.config.shift_factor is not None
                else 0.0
            )
        if hasattr(self.vae.config, "scaling_factor"):
            if verbose:
                print(f"VAE config scaling_factor: {self.vae.config.scaling_factor}")
            scaling_factor = (
                self.vae.config.scaling_factor
                if self.vae.config.scaling_factor is not None
                else 1.0
            )
        latents = (latents - shift_factor) * scaling_factor

        # 添加噪声直至指定step
        self.scheduler.set_timesteps(total_inference_steps, device=latents.device)
        timesteps = self.scheduler.timesteps
        if isinstance(timesteps, torch.Tensor):
            timesteps = timesteps.tolist()
        if step < 0 or step >= len(timesteps):
            raise ValueError(
                f"step {step} out of range for scheduler.timesteps (len={len(timesteps)})"
            )
        t = timesteps[step]
        if not torch.is_tensor(t):
            batch_size = latents.shape[0]
            t_tensor = torch.full(
                (batch_size,), t, device=latents.device, dtype=torch.long
            )
        else:
            t_tensor = t.to(latents.device)
        noise = randn_tensor(
            latents.shape,
            generator=generator,
            device=latents.device,
            dtype=latents.dtype,
        )
        noisy_latents = self.scheduler.add_noise(latents, noise, t_tensor)
        return noisy_latents

